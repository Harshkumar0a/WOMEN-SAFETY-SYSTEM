import { NextResponse } from "next/server";
import { createClient } from "@supabase/supabase-js";
import nodemailer from "nodemailer";

export async function POST(request: Request) {
  try {
    const { latitude, longitude } = await request.json();

    // 1. Extract Bearer token from Authorization header
    const authHeader = request.headers.get("authorization") || "";
    const token = authHeader.replace("Bearer ", "").trim();

    if (!token) {
      return NextResponse.json(
        { message: "Unauthorized. Missing session token." },
        { status: 401 }
      );
    }

    // 2. Initialize private Server client for auth operations
    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

    if (!supabaseUrl || !supabaseAnonKey) {
      return NextResponse.json(
        { message: "Server configuration error. Missing credentials." },
        { status: 500 }
      );
    }

    const supabaseServer = createClient(supabaseUrl, supabaseAnonKey, {
      auth: {
        persistSession: false,
        autoRefreshToken: false,
      },
    });

    // 3. Get user object securely using token
    const { data: { user }, error: userError } = await supabaseServer.auth.getUser(token);

    if (userError || !user) {
      return NextResponse.json(
        { message: "Invalid session token or user not authenticated." },
        { status: 401 }
      );
    }

    // 4. Fetch emergency email from Profiles table
    let emergencyEmail = "";
    const { data: profile, error: profileError } = await supabaseServer
      .from("profiles")
      .select("emergency_email")
      .eq("id", user.id)
      .single();

    if (profileError || !profile?.emergency_email) {
      // Fallback: Check raw user metadata if profile table doesn't have it
      const fallbackEmail = user.user_metadata?.emergency_email;
      if (!fallbackEmail) {
        return NextResponse.json(
          { message: "Please configure an emergency email in your profile to trigger SOS." },
          { status: 400 }
        );
      }
      emergencyEmail = fallbackEmail;
    } else {
      emergencyEmail = profile.emergency_email;
    }

    // 5. Log the SOS Alert in the database (defaults category to 'URGENT')
    const { error: insertError } = await supabaseServer.from("sos_alerts").insert({
      user_id: user.id,
      latitude: latitude || 0.0,
      longitude: longitude || 0.0,
      category: "URGENT",
    });

    if (insertError) {
      console.error("Failed to log SOS alert to database:", insertError.message);
    }

    // 6. Nodemailer Integration
    const emailUser = process.env.EMAIL_USER;
    const emailPass = process.env.EMAIL_PASS;

    if (!emailUser || !emailPass) {
      return NextResponse.json(
        { message: "SMTP Nodemailer user/password configuration is missing on server." },
        { status: 500 }
      );
    }

    // Create transporter using standard Gmail SMTP settings
    const transporter = nodemailer.createTransport({
      host: "smtp.gmail.com",
      port: 465,
      secure: true, // true for port 465
      auth: {
        user: emailUser,
        pass: emailPass,
      },
    });

    const mapsUrl = `https://maps.google.com/?q=${latitude || 0.0},${longitude || 0.0}`;
    const emailHtml = `
      <div style="font-family: sans-serif; padding: 20px; max-width: 600px; border: 2px solid #ef4444; border-radius: 10px;">
        <h2 style="color: #dc2626; font-size: 24px; font-weight: bold; margin-bottom: 10px;">🚨 URGENT SOS TRIGGERED! 🚨</h2>
        <p style="font-size: 16px; line-height: 1.6; color: #1f2937;">
          I am in an emergency situation and need immediate help. Please check on me or contact the local authorities.
        </p>
        <div style="margin: 20px 0; padding: 15px; background-color: #fef2f2; border-left: 4px solid #ef4444; border-radius: 6px;">
          <strong style="display: block; font-size: 14px; text-transform: uppercase; color: #b91c1c; margin-bottom: 10px;">My Live Location Link:</strong>
          <a href="${mapsUrl}" target="_blank" style="display: inline-block; padding: 12px 24px; font-weight: bold; color: #ffffff; background-color: #dc2626; text-decoration: none; border-radius: 9999px;">
            📍 Open Google Maps Location
          </a>
          <span style="display: block; font-size: 11px; color: #6b7280; margin-top: 10px;">Coordinates: ${latitude || 0.0}, ${longitude || 0.0}</span>
        </div>
        <p style="font-size: 12px; color: #6b7280; border-top: 1px solid #e5e7eb; padding-top: 10px; margin-top: 20px;">
          This is an automated alert generated by the Guardian Angel Women Safety System.
        </p>
      </div>
    `;

    // Send mail with defined transport object
    await transporter.sendMail({
      from: `"Guardian Angel Safety System" <${emailUser}>`,
      to: emergencyEmail,
      subject: "🚨 URGENT SOS TRIGGERED! 🚨",
      html: emailHtml,
    });

    return NextResponse.json({
      message: "SOS Emergency Alert Email successfully dispatched!",
      success: true,
      log_status: insertError ? "Failed to log" : "Logged",
    });
  } catch (err: any) {
    console.error("Trigger SOS endpoint crash:", err);
    return NextResponse.json(
      { message: err?.message || "Unexpected internal error during email dispatch." },
      { status: 500 }
    );
  }
}
